/** Per-dimension thematic percentage within a timeline bucket. */
export interface TimelineThemeBreakdown {
  dimension: LifeDimension;
  /** 0-100 share of evidence within the bucket for this dimension. */
  percent: number;
  /** Tag IDs contributing to this dimension share. */
  tagIds: string[];
}

/** A notable milestone event anchored within a timeline bucket. */
export interface TimelineMilestoneEntry {
  id: string;
  label: string;
  /** Unix ms timestamp of when the milestone occurred. */
  occurredAt: number;
  dimension?: LifeDimension;
}

/**
 * One time bucket in the Life Timeline cache.
 * Stored in `bie_timeline` (rebuildable; contentHash invalidation).
 *
 * `contentHash` = SHA-1 of all contributing evidence IDs in this period.
 * On cache miss or hash mismatch → rebuild from evidence store.
 */
export interface TimelineEntry {
  /**
   * Period key (PK in bie_timeline). Examples:
   *   - Month:   "2026-05"
   *   - Quarter: "2026-Q2"
   *   - Year:    "2026"
   */
  periodKey: string;
  /** Granularity of this bucket. */
  granularity: TimelineGranularity;
  /** Dimension-by-dimension thematic breakdown for this period. */
  themeBreakdown: TimelineThemeBreakdown[];
  /** Notable milestones that occurred in this period. */
  milestones: TimelineMilestoneEntry[];
  /** Unix ms timestamp of when this entry was generated / last rebuilt. */
  generatedAt: number;
  /**
   * SHA-1 of all contributing evidence IDs for this period.
   * Used for cache invalidation — if evidence changes, hash changes → rebuild.
   */
  contentHash: string;
}

/**
 * IndexedDB storage row for `bie_timeline` table.
 * Structurally identical to TimelineEntry (timeline cache is not HITL-gated).
 */
export interface TimelineRow extends TimelineEntry {}
