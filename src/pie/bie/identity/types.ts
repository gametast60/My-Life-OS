/**
 * A single insight generated by the InsightGenerator engine (Phase 4D S25).
 * Stored in `bie_insights` (FIFO 100 cap).
 *
 * HITL invariant (P4-12): `applied` is a literal `false` on the domain
 * object — only the DB row (`InsightRow`) relaxes this to `boolean`.
 */
export interface InsightItem {
  /** UUID for the insight record. */
  id: string;
  /** 6-type classification driving display + filtering. */
  type: InsightType;
  /** Thai-language display title for the Confirm UI. */
  title: string;
  /** Thai-language descriptive body text. */
  description: string;
  /** 0-1 AI confidence score. */
  confidence: number;
  /**
   * Arbitrary structured metrics context (e.g. period, delta values, σ).
   * Typed as opaque Record for extensibility; concrete payloads defined per type.
   */
  dataContext: Record<string, unknown>;
  /** Unix ms timestamp of generation. */
  generatedAt: number;
  /**
   * 🔒 ALWAYS `false` (P4-12 HITL invariant).
   * Becomes `true` only after User Confirm.
   */
  readonly applied: false;
}

/**
 * IndexedDB storage row for `bie_insights` table.
 * Relaxes `applied` to `boolean` for DB serialisation.
 */
export interface InsightRow extends Omit<InsightItem, "applied"> {
  applied: boolean;
}

