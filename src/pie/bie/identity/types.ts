/**
 * Canonical 6-type insight classification for the Identity Layer.
 * Distinct from the broader `InsightKind` union in bie/types.ts —
 * this enum drives the InsightGenerator pipeline in S25.
 */
export type InsightType =
  | "reflection"
  | "pattern"
  | "milestone"
  | "gap"
  | "conflict"
  | "prediction";

/**
 * Timeline bucket granularity — month / quarter / year view.
 * Mirrors `TimelinePeriodKind` in bie/types.ts for identity-layer locality.
 */
export type TimelineGranularity = "month" | "quarter" | "year";

// ─────────────────────────────────────────────────────────────────────
// Identity Singleton
// ─────────────────────────────────────────────────────────────────────

/**
 * A single scored entry within an identity category (e.g. one core value).
 * `evidenceIds` link back to BrainEvidence records for traceability.
 */
export interface IdentityEntry {
  /** Human-readable label (Thai or English as authored). */
  label: string;
  /** 0-1 AI confidence derived from evidence weight & recency. */
  confidence: number;
  /** IDs of BrainEvidence records backing this entry. */
  evidenceIds: string[];
}

/**
 * Full identity profile aggregate across 8 canonical categories.
 * Singleton: exactly one row per user (`id = "singleton"`).
 *
 * HITL invariant (P4-12): `applied` MUST be `false` on every newly
 * generated profile until the user explicitly confirms in the Confirm UI.
 */
export interface IdentityProfile {
  /** Always "singleton" — one row per user in `bie_identity` table. */
  readonly id: "singleton";
  /** Core personal values (e.g. "freedom", "family", "growth"). */
  coreValues: IdentityEntry[];
  /** Active life goals with timeframe context. */
  goals: IdentityEntry[];
  /** Intrinsic motivations that drive behaviour. */
  motivations: IdentityEntry[];
  /** Personality traits (e.g. "introverted", "systematic"). */
  personality: IdentityEntry[];
  /** Observed personal strengths. */
  strengths: IdentityEntry[];
  /** Identified personal weaknesses / growth areas. */
  weaknesses: IdentityEntry[];
  /** Recurring thinking & decision-making patterns. */
  thinkingPattern: IdentityEntry[];
  /** Free-form AI-generated rollup summary paragraph. */
  summary: string;
  /** Unix ms timestamp of when this profile was generated. */
  generatedAt: number;
  /**
   * 🔒 ALWAYS `false` on creation (P4-12 HITL invariant).
   * Becomes `true` only after explicit User Confirm in the Confirm UI.
   */
  readonly applied: false;
}

/**
 * IndexedDB storage row for `bie_identity` table.
 * Extends IdentityProfile with a serialisable `applied` flag (db can store
 * boolean; the runtime domain type constrains it to `false` pre-confirm).
 */
export interface IdentityRow extends Omit<IdentityProfile, "applied"> {
  applied: boolean;
}

